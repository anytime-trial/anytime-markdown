-- 027: 知識グラフのノードに有効エッジ次数を持たせる。
--
-- 視野（bbox）で絞る問い合わせが、次数を数えるために caravan_edges を全走査していた。
-- 実測（合成 100,000 ノード / 200,000 リンク・2026-08-08）では、視野を 2% まで絞っても
-- 応答は 4.4 秒で、全体（2.7 秒）より遅い。視野の条件が走査を減らさず、両端の EXISTS を
-- 足すだけだったため。
--
-- 次数を座標と一緒に持てば、視野内のノード選定は (x, y) 索引の範囲走査だけで済み、
-- caravan_edges を引くのは「選ばれた候補同士のリンク」を取る時だけになる（候補数に比例）。
--
-- 既定 0 は「レイアウト未計算」ではなく「エッジを持たない」を表す。レイアウトは
-- エッジを持つノードにしか行を作らないため、実際に 0 が残るのは本 migration 適用直後の
-- 既存行だけで、次のパイプライン実行で全行が書き替わる。

ALTER TABLE caravan_entity_layout ADD COLUMN degree INTEGER NOT NULL DEFAULT 0;
