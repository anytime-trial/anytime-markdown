-- 033: レビュー指摘の対象パスが「明示されたもの」か「推測で埋めたもの」かを区別する。
--
-- 第 2 段で、対象パスが空の指摘について本文中の裸のファイル名（`cli.ts` 等）から
-- リポジトリ相対パスを一意解決して埋める（resolveMissingFindingPaths）。この列が無いと、
-- 埋めた瞬間に「レビュアーが対象を書いた指摘」と区別できなくなる。
--
-- 区別が要るのは、推測由来には固有の失敗モードがあるため。activity_commit_files は
-- 履歴上のパスを保持するので、移動済みファイルの旧パスへ一意解決し得る。その指摘は
-- 誤リンクにはならないが「以後どのコミットとも一致しない死んだ対象」になり、追跡対象に
-- 数えられたまま永久に未対処として残る。混ざったまま集計すると、対処率が下がった原因が
-- 「本当に直していない」なのか「推測が外れた」なのか読めない。
--
-- NULL = レビュアーが対象を明示した（または旧データ）。'basename' = 本文の裸ファイル名から
-- 一意解決した。将来の推測経路を足すときは値を増やす（CHECK は ADD COLUMN では挿入・
-- 更新時にのみ効くため、既存行の NULL は検査対象外で問題ない）。

ALTER TABLE caravan_review_findings
  ADD COLUMN target_inferred_by TEXT
    CHECK (target_inferred_by IS NULL OR target_inferred_by IN ('basename'));
